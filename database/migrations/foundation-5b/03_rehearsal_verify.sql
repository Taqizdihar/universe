FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA='uniin_universe_reh' AND CONSTRAINT_TYPE='PRIMARY KEY';
SELECT tc.TABLE_NAME, tc.CONSTRAINT_NAME, tc.CONSTRAINT_TYPE
FROM information_schema.TABLE_CONSTRAINTS tc
WHERE tc.CONSTRAINT_SCHEMA='uniin_universe_reh' AND tc.CONSTRAINT_TYPE IN ('PRIMARY KEY','UNIQUE','CHECK')
ORDER BY tc.TABLE_NAME, tc.CONSTRAINT_TYPE, tc.CONSTRAINT_NAME;
SELECT COUNT(DISTINCT CONCAT(k.TABLE_NAME, '.', k.CONSTRAINT_NAME)) AS foreign_key_count,
       CASE WHEN COUNT(DISTINCT CONCAT(k.TABLE_NAME, '.', k.CONSTRAINT_NAME))=30 THEN 'PASS' ELSE 'FAIL' END AS foreign_key_check
FROM information_schema.KEY_COLUMN_USAGE k
WHERE k.TABLE_SCHEMA='uniin_universe_reh' AND k.REFERENCED_TABLE_NAME IS NOT NULL;
SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION, k.COLUMN_NAME,
       k.REFERENCED_TABLE_SCHEMA, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME,
       r.DELETE_RULE AS on_delete, r.UPDATE_RULE AS on_update
FROM information_schema.KEY_COLUMN_USAGE k
JOIN information_schema.REFERENTIAL_CONSTRAINTS r
  ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
WHERE k.TABLE_SCHEMA='uniin_universe_reh' AND k.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY k.TABLE_NAME,k.CONSTRAINT_NAME,k.ORDINAL_POSITION;
SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.REFERENCED_TABLE_SCHEMA AS unexpected_schema
FROM information_schema.KEY_COLUMN_USAGE k
WHERE k.TABLE_SCHEMA='uniin_universe_reh' AND k.REFERENCED_TABLE_NAME IS NOT NULL
  AND k.REFERENCED_TABLE_SCHEMA<>'uniin_universe_reh';
SELECT tc.TABLE_NAME, tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE
FROM information_schema.TABLE_CONSTRAINTS tc
JOIN information_schema.CHECK_CONSTRAINTS cc
  ON cc.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA AND cc.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_SCHEMA='uniin_universe_reh' AND tc.CONSTRAINT_TYPE='CHECK'
ORDER BY tc.TABLE_NAME,tc.CONSTRAINT_NAME;
SELECT COUNT(*) AS check_constraint_count,
