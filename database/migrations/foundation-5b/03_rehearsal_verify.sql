       EXTRA, CHARACTER_SET_NAME, COLLATION_NAME
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='uniin_universe_reh' ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT COUNT(*) AS auto_increment_column_count,
       CASE WHEN COUNT(*)=25 THEN 'PASS' ELSE 'FAIL' END AS auto_increment_check
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='uniin_universe_reh' AND EXTRA LIKE '%auto_increment%';
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COLUMN_NAME, INDEX_TYPE
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='uniin_universe_reh' ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;
